WITH session_pairs AS
(
    SELECT
        user_id,
        DATE(session_time) AS session_date,
        session_time AS start_time,
        LEAD(session_time) OVER (PARTITION BY user_id ORDER BY session_time) AS end_time,
        state
    FROM user_sessions
)
SELECT
    user_id,
    session_date,
    ROUND(SUM(TIMESTAMPDIFF(MINUTE, start_time, end_time)) / 60,2) AS total_hours
FROM session_pairs
WHERE state = 1
GROUP BY user_id, session_date
ORDER BY user_id, session_date;