3       | 2025-08-03 | 120
4       | 2025-08-04 | 200
5       | 2025-08-05 | 80
6       | 2025-08-06 | 90
7       | 2025-08-07 | 160
8       | 2025-08-08 | 130
9       | 2025-08-09 | 140
10      | 2025-08-10 | 170

Output:

sale_date  | amount | rolling_7_day_avg
------------|--------|-------------------
2025-08-01 | 100    | 100.00
2025-08-02 | 150    | 125.00
2025-08-03 | 120    | 123.33
2025-08-04 | 200    | 142.50
2025-08-05 | 80     | 130.00
2025-08-06 | 90     | 123.33
2025-08-07 | 160    | 128.57
2025-08-08 | 130    | 132.86
2025-08-09 | 140    | 131.43
2025-08-10 | 170    | 138.57
*/


CREATE or replace TABLE sales321 (
    sale_id INT,
    sale_date DATE,
    amount DECIMAL(10,2)
);

INSERT INTO sales321 VALUES
(1, '2025-08-01', 100.00),
(2, '2025-08-02', 150.00),
(3, '2025-08-03', 120.00),
(4, '2025-08-04', 200.00),
(5, '2025-08-05', 80.00),
(6, '2025-08-06', 90.00),
(7, '2025-08-07', 160.00),
(8, '2025-08-08', 130.00),
(9, '2025-08-09', 140.00),
(10, '2025-08-10', 170.00);


SELECT 
    sale_date,
    amount,
    ROUND(AVG(amount) OVER (ORDER BY sale_date ROWS BETWEEN 6 PRECEDING AND CURRENT ROW), 2) AS rolling_7_day_avg
FROM 
    sales321
ORDER BY sale_date;
